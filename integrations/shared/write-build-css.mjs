import {
  existsSync,
  mkdirSync,
  readFileSync,
  renameSync,
  unlinkSync,
  writeFileSync,
} from "fs";
import { buildManifestModuleSource } from "./build-manifest.mjs";
import { assertValidGeneratedCss } from "./validate-build-css.mjs";
import {
  cssCacheArtifactsForIntegration,
  iuiCacheDir,
  iuiCacheFile,
} from "./iui-paths.mjs";

/**
 * Client-side fallback injector (Webpack entry / HtmlWebpackPlugin unavailable).
 * Preferred path is HTML/head injection or a linked stylesheet.
 * @param {string} css
 */
export function buildStylesInjectorSource(css) {
  const body = css ?? "";
  return `/** Auto-generated by @inventive-ui/framework — do not edit */
const css = ${JSON.stringify(body)};
globalThis.__IUI_BUILD_CSS__ = css;
export default css;
if (typeof document !== "undefined" && document.head) {
  let el = document.querySelector("style[data-iui-build]");
  if (!el) {
    el = document.createElement("style");
    el.setAttribute("data-iui-build", "");
    document.head.prepend(el);
  }
  if (el.textContent !== css) {
    el.textContent = css;
  }
}
`;
}

/**
 * SSR bootstrap snippet — sets globalThis.__IUI_BUILD_CSS__ before React hydrates.
 * @param {string} css
 */
export function buildCssInlineBootstrapSource(css) {
  return `/** Auto-generated by @inventive-ui/framework — do not edit */
globalThis.__IUI_BUILD_CSS__ = ${JSON.stringify(css ?? "")};
export {};
`;
}

/**
 * @param {string} filePath
 * @param {string} contents
 * @returns {boolean} true when the file was written
 */
function writeFileIfChanged(filePath, contents) {
  if (existsSync(filePath)) {
    try {
      if (readFileSync(filePath, "utf8") === contents) {
        return false;
      }
    } catch {
      // Fall through and rewrite.
    }
  }
  const tempPath = `${filePath}.${process.pid}.${Date.now()}.${Math.random()
    .toString(16)
    .slice(2)}.tmp`;
  writeFileSync(tempPath, contents, "utf8");
  try {
    renameSync(tempPath, filePath);
  } finally {
    if (existsSync(tempPath)) {
      try {
        unlinkSync(tempPath);
      } catch {
        // best-effort temp cleanup
      }
    }
  }
  return true;
}

/** @param {import("./iui-paths.mjs").IuiBuildIntegration} integration */
function pruneAdapterCssCache(projectRoot, integration) {
  const allowed = new Set(cssCacheArtifactsForIntegration(integration));
  for (const key of ["stylesInject", "stylesInline"]) {
    if (allowed.has(key)) continue;
    const stalePath = iuiCacheFile(projectRoot, key);
    if (!existsSync(stalePath)) continue;
    try {
      unlinkSync(stalePath);
    } catch {
      // Best-effort — stale adapter files are harmless if removal fails.
    }
  }
}

/**
 * Writes compile-first CSS artifacts under `.iui/cache/` for the active integration.
 * Each bundler adapter generates only the cache files it consumes.
 *
 * @param {string} projectRoot
 * @param {{ combinedCSS: string, manifest: Record<string, unknown> }} payload
 * @param {{ integration?: import("./iui-paths.mjs").IuiBuildIntegration }} [options]
 */
export function writeBuildCssFiles(projectRoot, payload, options = {}) {
  const integration = options.integration ?? "webpack";
  const artifacts = new Set(cssCacheArtifactsForIntegration(integration));
  const outDir = iuiCacheDir(projectRoot);
  mkdirSync(outDir, { recursive: true });

  const css = payload.combinedCSS ?? "";
  const manifest = payload.manifest ?? {};

  assertValidGeneratedCss(css, {
    source: "IUI .iui/cache/styles.css",
  });

  const written = {};

  if (artifacts.has("styles")) {
    const cssFile = iuiCacheFile(projectRoot, "styles");
    writeFileIfChanged(cssFile, css);
    written.cssFile = cssFile;
  }

  if (artifacts.has("manifest")) {
    const manifestJs = iuiCacheFile(projectRoot, "manifest");
    writeFileIfChanged(manifestJs, buildManifestModuleSource(manifest));
    written.manifestJs = manifestJs;
  }

  if (artifacts.has("stylesInject")) {
    const stylesJs = iuiCacheFile(projectRoot, "stylesInject");
    writeFileIfChanged(stylesJs, buildStylesInjectorSource(css));
    written.stylesJs = stylesJs;
  }

  if (artifacts.has("stylesInline")) {
    const inlineBootstrap = iuiCacheFile(projectRoot, "stylesInline");
    writeFileIfChanged(inlineBootstrap, buildCssInlineBootstrapSource(css));
    written.inlineBootstrap = inlineBootstrap;
  }

  pruneAdapterCssCache(projectRoot, integration);

  return written;
}
