/**
 * Compile-first build manifest (not user-facing modes).
 * Keep fields content-stable — wall-clock timestamps invalidate Vite HMR for every
 * importer of `iui-build-manifest` even when `cssHash` is unchanged.
 *
 * @param {{ cssHash: string, classCount: number, themeBytes?: number, utilityBytes?: number, combinedBytes?: number, themeInitHash?: string }} stats
 */
export function createBuildManifest(stats) {
  return {
    mode: "compile",
    version: 1,
    cssHash: stats.cssHash ?? "",
    classCount: stats.classCount ?? 0,
    themeBytes: stats.themeBytes ?? 0,
    utilityBytes: stats.utilityBytes ?? 0,
    combinedBytes: stats.combinedBytes ?? 0,
    themeInitHash: stats.themeInitHash ?? "",
  };
}

/** Stub when bundler plugin is absent — legacy runtime path unchanged. */
export function createRuntimeManifestStub() {
  return {
    mode: "runtime",
    version: 1,
    cssHash: "",
    classCount: 0,
    themeBytes: 0,
    utilityBytes: 0,
    combinedBytes: 0,
    generatedAt: "",
  };
}

/**
 * @param {Record<string, unknown>} manifest
 */
export function buildManifestModuleSource(manifest) {
  return `/** Auto-generated by @inventive-ui/framework — do not edit */
globalThis.__IUI_BUILD__ = ${JSON.stringify(manifest)};
export const IUI_BUILD = globalThis.__IUI_BUILD__;
export default IUI_BUILD;
`;
}

/**
 * @param {string} css
 */
export function buildStylesModuleSource(css) {
  const body = css ?? "";
  return `/** Auto-generated by @inventive-ui/framework — do not edit */
export default ${JSON.stringify(body)};
`;
}

