/**
 * Builds the `iui-slot-warmup` module source from a scanned asset registry.
 * Used by Vite (virtual module) and Webpack (`.iui/slot-warmup.generated.mjs`).
 */

export function buildWarmupModuleSource(importIds) {
  const unique = [...new Set(importIds)].filter(Boolean).sort();

  if (unique.length === 0) {
    return `export async function warmScannedSlotAssets() {}
export default warmScannedSlotAssets;
`;
  }

  const loaders = unique
    .map((id) => `  import(${JSON.stringify(id)}).catch(() => {}),`)
    .join("\n");

  return `/** Auto-generated by @inventive-ui/framework — do not edit */
export async function warmScannedSlotAssets() {
  await Promise.all([
${loaders}
  ]);
}
export default warmScannedSlotAssets;
`;
}

export function collectWarmupImportIds(registry, projectRoot, lookupKeyToModuleId, resolveAssetSubpath) {
  const ids = [];
  for (const [pkg, keys] of registry.entries()) {
    for (const key of keys) {
      const modId = lookupKeyToModuleId(pkg, key);
      if (modId && resolveAssetSubpath(projectRoot, modId)) {
        ids.push(modId);
      }
    }
  }
  return ids;
}
