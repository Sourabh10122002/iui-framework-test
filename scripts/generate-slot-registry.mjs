/**
 * Slot Registry Generator
 * -----------------------
 *
 * This script automatically generates a TypeScript file that imports
 * all `.slot.tsx` files as side effects.
 *
 * WHY THIS EXISTS:
 * ----------------
 * - Rollup cannot dynamically discover files at runtime.
 * - Slot renderers rely on side-effect registration (`registerSlot(...)`).
 * - We want ZERO manual index files (no merge conflicts).
 *
 * HOW IT WORKS:
 * -------------
 * 1. Scans `src/utilities/slot/` for `*.slot.tsx` files.
 * 2. Generates `__generated__.ts` with import statements for each slot file.
 * 3. Importing `__generated__.ts` guarantees all slots are registered.
 *
 * WHEN IT RUNS:
 * -------------
 * - Before `npm run dev` (development)
 * - Before `npm run build` (Rollup)
 *
 * IMPORTANT:
 * ----------
 * - This file is auto-generated.
 * - Do NOT edit `__generated__.ts` manually.
 */

import fs from "fs";
import path from "path";
import { globSync } from "glob";

/**
 * Absolute path to the directory containing all slot definitions.
 *
 * Expected structure:
 * src/utilities/slot/
 *   ├─ icon.slot.tsx
 *   ├─ text.slot.tsx
 *   ├─ ...
 */
const slotsDir = path.resolve("src/utilities/slot");

/**
 * Output file that will contain side-effect imports
 * for all discovered slot files.
 *
 * This file is later imported by the library entry point
 * to ensure all slots are registered at runtime.
 */
const outFile = path.resolve("src/.generated/slot-registry.ts");

// Ensure output directory exists
const outDir = path.dirname(outFile);
if (!fs.existsSync(outDir)) {
  fs.mkdirSync(outDir, { recursive: true });
}

/**
 * Find all slot definition files.
 *
 * - Uses glob to match any `*.slot.tsx` file.
 * - `cwd` ensures relative paths for clean imports.
 * - `nodir` avoids directory matches.
 */
const files = globSync("**/*.slot.tsx", {
  cwd: slotsDir,
  nodir: true,
});

/**
 * Include ALL slot files. Slot registrations use try/catch and dynamic import()
 * to handle missing optional packages (return Empty component). Excluding
 * slots at build time would prevent consumers who have those packages from
 * ever getting the renderers.
 */
const includedFiles = files;

// Ensure we have at least an empty array if no files found
if (includedFiles.length === 0) {
  console.warn("⚠️  No slot files found in src/utilities/slot/");
}

/**
 * Convert discovered slot files into side-effect import statements.
 *
 * Example:
 *   icon.slot.tsx  →  import "../icon.slot.tsx";
 */
const imports = includedFiles.length > 0
  ? includedFiles
  .map((file) => `import "../utilities/slot/${file.replace(/\\/g, "/")}";`)
      .join("\n")
  : "// No slot files found";

/**
 * Final file content.
 *
 * NOTE:
 * - This file contains NO exports.
 * - Importing it executes slot registration via side effects.
 * - Always generates a valid file, even if no slots exist.
 */
// Always generate a valid TypeScript file, even if empty
const content = `// ⚠️ AUTO-GENERATED — DO NOT EDIT
// This file is automatically generated by scripts/generate-slot-registry.mjs
// Do not edit this file manually. Run 'npm run prebuild' to regenerate.

${imports}

${includedFiles.length > 0 ? "// Slots registered automatically" : '// No slots to register - this is a valid empty file'}
export {};
`;

/**
 * Write the generated registry file to disk.
 * This will overwrite any existing version.
 */
fs.writeFileSync(outFile, content);

/**
 * Log success for developer feedback.
 */
console.log("✅ Slot registry generated");

